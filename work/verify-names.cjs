const {chromium}=require('playwright');
const fs=require('fs'),assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1365,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.ATLAS_URL||require('url').pathToFileURL(require('path').resolve('outputs/index.html')).href);
 assert.equal(await page.locator('#names').count(),0);
 await page.fill('#pw',fs.readFileSync('outputs/Пароль к семейному атласу.txt','utf8').trim());
 await page.click('#unlock');
 await page.waitForSelector('#names');
 await page.locator('a[href="#names"]').first().click();
 assert.match(await page.locator('#names-coverage').textContent(),/884 из 903/);
 assert.equal(await page.locator('#names-male .name-bar').count(),10);
 assert.match(await page.locator('#names-male .name-bar').first().textContent(),/Иван.*47/);
 assert.match(await page.locator('#names-female .name-bar').first().textContent(),/Мария.*38/);
 await page.locator('#names-male .name-bar').first().click();
 assert.equal(await page.locator('#names-people button').count(),47);
 await page.locator('#names-people button').first().click();
 assert(await page.locator('#kin-focus').isVisible());
 await page.selectOption('#names-scope','all');
 assert.match(await page.locator('#names-coverage').textContent(),/903 из 903/);
 await page.selectOption('#names-limit','999');
 assert(await page.locator('#names-male .name-bar').count()>90);
 await page.selectOption('#names-scope','main');
 await page.selectOption('#names-limit','10');
 await page.locator('#names').scrollIntoViewIfNeeded();
 await page.screenshot({path:'work/names-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#names').scrollIntoViewIfNeeded();
 assert(await page.locator('#names').evaluate(e=>e.scrollWidth<=e.clientWidth+1));
 await page.screenshot({path:'work/names-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log(await page.locator('#names-coverage').textContent());
 console.log(await page.locator('#names-metrics').innerText());
 await browser.close();
 console.log('Names charts, filters, person navigation, encryption and mobile layout passed.');
})().catch(e=>{console.error(e);process.exit(1)});
